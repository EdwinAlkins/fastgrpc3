def registry_of(*methods: MethodDef, package: str = "shop.v1") -> SchemaRegistry:
    registry = SchemaRegistry()
    registry.add_service(ServiceDef("Shop", package, methods))
    return registry


def rpc(request: type[BaseModel], response: type[BaseModel] | None = None) -> MethodDef:
    return MethodDef(f"Call{request.__name__}", request, response or request)


# The models of the fastgrpc2 analysis (docs/fastgrpc2/02-api-publique.md): rendering and
# compiling them is the end criterion of phase 4.
@proto_enum(NEW=0, PAID=1)
class Status(enum.Enum):
    NEW = "new"
    PAID = "paid"


class GetOrderRequest(BaseModel):
    order_number: str = Field(min_length=1)


class OrderReply(BaseModel):
    order_number: str = key(2)
    status: Status = key(1)
    note: str | None = key(3, default=None)


class Pinned(BaseModel):
    id: Annotated[str, ProtoField(1)]


def test_fastgrpc2_analysis_models_render_and_compile() -> None:
    registry = SchemaRegistry()
    registry.add_service(
        ServiceDef(
            "Orders",
            "orders.v1",
            (
                MethodDef("GetOrder", GetOrderRequest, OrderReply),
                MethodDef("Watch", GetOrderRequest, OrderReply, server_streaming=True),
                MethodDef("Upload", GetOrderRequest, OrderReply, client_streaming=True),
                MethodDef("Chat", GetOrderRequest, OrderReply, True, True),
                MethodDef("Pin", Pinned, Pinned),
            ),
        )
    )
    schema = Schema.from_registry(registry)

    assert schema.files == {
        "orders/v1/orders.proto": """\
// Generated by fastgrpc3 from Python models: edit the models, not this file.
syntax = "proto3";

package orders.v1;

enum Status {
  STATUS_NEW = 0;
  STATUS_PAID = 1;
}

message GetOrderRequest {
  string order_number = 1;
}

message OrderReply {
  string order_number = 2;
  Status status = 1;
  optional string note = 3;
}

message Pinned {
  string id = 1;
}

service Orders {
  rpc GetOrder(GetOrderRequest) returns (OrderReply);
  rpc Watch(GetOrderRequest) returns (stream OrderReply);
  rpc Upload(stream GetOrderRequest) returns (OrderReply);
  rpc Chat(stream GetOrderRequest) returns (stream OrderReply);
  rpc Pin(Pinned) returns (Pinned);
}
"""
    }
    method = schema.info.service("orders.v1.Orders").method("Chat")
    assert (method.client_streaming, method.server_streaming) == (True, True)
    assert schema.info.message("orders.v1.OrderReply").field("note").has_presence


class Card(ProtoModel, package="pay.v1"):
    """A payment card."""

    number: str = field(1, description="Card number.\nNever logged.")


class Payment(ProtoModel, proto="pay.v1.Payment"):
    card: Card | None = field(1, default=None, oneof="method")
    iban: str | None = field(2, default=None, oneof="method")
    amount: Int32 = field(3, default=0)


class Checkout(BaseModel):
    payment: Payment
    at: datetime.datetime | None = None
    on: datetime.date | None = None
    tags: dict[str, int] = {}


def test_packages_imports_oneof_and_comments() -> None:
    schema = Schema.from_registry(registry_of(rpc(Checkout)))

    assert list(schema.files) == ["shop/v1/shop.proto", "pay/v1/pay.proto"]
    shop = schema.files["shop/v1/shop.proto"]
    assert 'import "google/protobuf/timestamp.proto";\nimport "google/type/date.proto";\n' in shop
    assert 'import "pay/v1/pay.proto";' in shop
    assert "  pay.v1.Payment payment = 1;\n" in shop
    assert "  map<string, int64> tags = 4;\n" in shop
    pay = schema.files["pay/v1/pay.proto"]
    assert "  oneof method {\n    Card card = 1;\n    string iban = 2;\n  }\n" in pay
    assert "// A payment card.\nmessage Card {\n  // Card number.\n  // Never logged.\n" in pay
    assert schema.info.message("pay.v1.Payment").field("iban").oneof == "method"


def test_reserved_numbers_and_names_are_rendered() -> None:
    class Order(BaseModel):
        a: str = ""

    lock = Lock({"shop.v1.Order": MessageLock({"a": 1}, [2, 3, 4, 7], ["old", "older"])})
    schema = Schema.from_registry(registry_of(rpc(Order)), lock)

    text = schema.files["shop/v1/shop.proto"]
    assert '  reserved 2 to 4, 7;\n  reserved "old", "older";\n' in text
    assert schema.info.message("shop.v1.Order").reserved_ranges == ((2, 4), (7, 7))


def test_enum_values_are_prefixed_with_zero_first_and_aliases_allowed() -> None:
    class OrderState(enum.IntEnum):
        PAID = 1
        UNKNOWN = 0
        SETTLED = 1  # alias of PAID

    class HTTPCode(ProtoEnum):
        HTTP_CODE_UNSPECIFIED = 0

    class Order(BaseModel):
        state: OrderState = OrderState.UNKNOWN
        code: HTTPCode = HTTPCode.HTTP_CODE_UNSPECIFIED

    text = Schema.from_registry(registry_of(rpc(Order))).files["shop/v1/shop.proto"]
    assert (
        "enum OrderState {\n"
        "  option allow_alias = true;\n"
        "  ORDER_STATE_UNKNOWN = 0;\n"
        "  ORDER_STATE_PAID = 1;\n"
        "  ORDER_STATE_SETTLED = 1;\n"
        "}\n"
    ) in text
    assert "enum HTTPCode {\n  HTTP_CODE_UNSPECIFIED = 0;\n}\n" in text


