@pytest.mark.parametrize(
    "command",
    [
        ["mypy", "--strict", "--no-incremental"],
        ["ruff", "check", "--isolated", "--select", "E,F,W,I,UP,B,SIM,RUF", "--ignore", "E501"],
        ["ruff", "format", "--isolated", "--line-length", "100", "--check"],
    ],
    ids=["mypy-strict", "ruff-check", "ruff-format"],
)
def test_generated_code_is_clean(package: tuple[str, Path], command: list[str]) -> None:
    """Criterion R1: generated code passes `mypy --strict`, and ruff has nothing to say."""
    executable = shutil.which(command[0], path=str(Path(sys.executable).parent))
    assert executable is not None
    result = subprocess.run(
        [executable, *command[1:], package[0]],
        cwd=package[1].parent,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr


def test_generated_models_bind_to_the_embedded_descriptor(package: tuple[str, Path]) -> None:
    models = load(package, "shop.v1.shop_models")
    service = load(package, "shop.v1.shop_service")
    descriptor = load(package, "_descriptor").DESCRIPTOR
    registry = SchemaRegistry()
    registry.add_service(service.Orders)
    schema = Schema.from_descriptor(registry, descriptor)

    order = models.Order(
        order_number="A",
        status=models.OrderStatus.PAID,
        created_at=datetime.datetime(2024, 1, 1, tzinfo=datetime.UTC),
        note="",
        lines=[models.Line(sku="s", qty=2)],
        counters={"k": 3},
        coupon="",
        meta={"a": 1.0},
        extra=[1.0, "x"],
        due=datetime.date(2024, 2, 29),
        card=models.Order_Card(number="4", kind=models.Order_Card_Kind.VISA),
        from_="Paris",
        json_=b"{}",
        color=models.Color.GREEN,
        delay=datetime.timedelta(seconds=5),
        mask=["a.b"],
        by_position={1: models.Line(sku="z")},
        limit=0,
    )
    codec = schema.codec(models.Order)
    encoded = codec.encode(order)
    assert codec.decode(encoded) == order
    # Plain protobuf on the wire, with the proto field names.
    wire = NativeCodec(descriptor, "shop.v1.Order").decode_dict(encoded)
    assert (wire["from"], wire["json"], wire["card"]["number"]) == ("Paris", b"{}", "4")


def test_models_out_of_date_with_the_descriptor_are_refused(package: tuple[str, Path]) -> None:
    descriptor = load(package, "_descriptor").DESCRIPTOR

    class Money(ProtoModel, proto="common.v1.Money"):
        currency: str = field(1, default="")
        units: str = field(2, default="")  # int64 in the descriptor

    registry = SchemaRegistry()
    registry.add_model(Money)
    with pytest.raises(SchemaError, match=r"common\.v1\.Money field 2: model singular string"):
        Schema.from_descriptor(registry, descriptor)


def test_write_removes_stale_files_and_check_reports_differences(
    files: dict[str, str], tmp_path: Path
) -> None:
    output = tmp_path / "gen"
    write(files, output)
    assert check(files, output) == []

    (output / "old_models.py").write_text("# Generated by fastgrpc3 from old.proto\n")
    (output / "mine.py").write_text("# written by hand\n")
    (output / "shop/v1/shop_models.py").write_text("# Generated by fastgrpc3, edited\n")
    (output / "common/v1/money_models.py").unlink()
    assert check(files, output) == [
        f"missing {output / 'common/v1/money_models.py'}",
        f"outdated {output / 'shop/v1/shop_models.py'}",
        f"stale {output / 'old_models.py'}",
    ]
    assert write(files, output) == [output / "old_models.py"]
    assert (output / "mine.py").exists()
    assert check(files, output) == []


def test_proto2_files_are_refused(tmp_path: Path) -> None:
    (tmp_path / "old.proto").write_text('syntax = "proto2"; package old; message M {}')
    with pytest.raises(CodegenError, match="only proto3"):
        generate([tmp_path])


def test_unsupported_well_known_types_are_refused(tmp_path: Path) -> None:
    (tmp_path / "api.proto").write_text(
        'syntax = "proto3"; package x; import "google/protobuf/api.proto";'
        "message M { google.protobuf.Api api = 1; }"
    )
    with pytest.raises(CodegenError, match=r"type google\.protobuf\.Api is not supported"):
        generate([tmp_path])


