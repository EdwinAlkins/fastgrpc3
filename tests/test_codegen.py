@pytest.mark.parametrize(
    "command",
    [
        ["mypy", "--strict", "--no-incremental"],
        ["ruff", "check", "--isolated", "--select", "E,F,W,I,UP,B,SIM,RUF", "--ignore", "E501"],
        ["ruff", "format", "--isolated", "--line-length", "100", "--check"],
    ],
    ids=["mypy-strict", "ruff-check", "ruff-format"],
)
def test_generated_code_is_clean(package: tuple[str, Path], command: list[str]) -> None:
    """Criterion R1: generated code passes `mypy --strict`, and ruff has nothing to say."""
    executable = shutil.which(command[0], path=str(Path(sys.executable).parent))
    assert executable is not None
    result = subprocess.run(
        [executable, *command[1:], package[0]],
        cwd=package[1].parent,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr


def test_generated_models_bind_to_the_embedded_descriptor(package: tuple[str, Path]) -> None:
    models = load(package, "shop.v1.shop_models")
    service = load(package, "shop.v1.shop_service")
    descriptor = load(package, "_descriptor").DESCRIPTOR
    registry = SchemaRegistry()
    registry.add_service(service.Orders)
    schema = Schema.from_descriptor(registry, descriptor)

    order = models.Order(
        order_number="A",
        status=models.OrderStatus.PAID,
        created_at=datetime.datetime(2024, 1, 1, tzinfo=datetime.UTC),
        note="",
        lines=[models.Line(sku="s", qty=2)],
        counters={"k": 3},
        coupon="",
        meta={"a": 1.0},
        extra=[1.0, "x"],
        due=datetime.date(2024, 2, 29),
        card=models.Order_Card(number="4", kind=models.Order_Card_Kind.VISA),
        from_="Paris",
        json_=b"{}",
        color=models.Color.GREEN,
        delay=datetime.timedelta(seconds=5),
        mask=["a.b"],
        by_position={1: models.Line(sku="z")},
        limit=0,
    )
    codec = schema.codec(models.Order)
    encoded = codec.encode(order)
    assert codec.decode(encoded) == order
    # Plain protobuf on the wire, with the proto field names.
    wire = NativeCodec(descriptor, "shop.v1.Order").decode_dict(encoded)
    assert (wire["from"], wire["json"], wire["card"]["number"]) == ("Paris", b"{}", "4")


