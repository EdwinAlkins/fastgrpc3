"""Render a `ResolvedSchema` as `.proto` text: one file per package, with its imports.

The text rendered here is exactly what gets compiled at startup and what `fastgrpc3
export` writes, so the exported contract never drifts from the served one.
"""

from collections.abc import Iterator

from fastgrpc3.schema.annotations import FieldSpec, TypeRef
from fastgrpc3.schema.registry import (
    EnumSpec,
    MessageSpec,
    ResolvedSchema,
    SchemaError,
    ServiceDef,
)

__all__ = ["package_file", "render"]

HEADER = "// Generated by fastgrpc3 from Python models: edit the models, not this file."
INDENT = "  "


def package_file(package: str) -> str:
    """File holding a package: `orders.v1` -> `orders/v1/orders.proto`."""
    parts = package.split(".")
    names = [part for part in parts if not _is_version(part)] or parts
    return "/".join(parts) + f"/{names[-1]}.proto"


def render(schema: ResolvedSchema) -> dict[str, str]:
    """`.proto` text of every package, keyed by file name."""
    imports = {package: _imports(schema, package) for package in schema.packages()}
    _check_no_cycle(imports)
    return {
        package_file(package): _render_package(schema, package, imports[package])
        for package in schema.packages()
    }


def _is_version(part: str) -> bool:
    return part.startswith("v") and part[1:2].isdigit()


def _imports(schema: ResolvedSchema, package: str) -> list[str]:
    files: set[str] = set()

    def add(ref: TypeRef) -> None:
        if ref.import_path is not None:
            files.add(ref.import_path)
        elif ref.kind in ("message", "enum"):
            other = schema.full_name(ref).rpartition(".")[0]
            if other != package:
                files.add(package_file(other))

    for message in schema.messages.values():
        if message.package == package:
            for spec in message.fields:
                add(spec.value)
    for service in schema.services:
        if service.package == package:
            for method in service.methods:
                add(TypeRef("message", py=method.request))
                add(TypeRef("message", py=method.response))
    return sorted(files)


def _check_no_cycle(imports: dict[str, list[str]]) -> None:
    by_file = {package_file(package): package for package in imports}
    state: dict[str, str] = {}

    def visit(package: str, path: list[str]) -> None:
        if state.get(package) == "done":
            return
        if state.get(package) == "active":
            cycle = " -> ".join([*path[path.index(package) :], package])
            raise SchemaError(f"packages import each other: {cycle}; move shared models")
        state[package] = "active"
        for file in imports[package]:
            if file in by_file:
                visit(by_file[file], [*path, package])
        state[package] = "done"

    for package in imports:
        visit(package, [])


def _render_package(schema: ResolvedSchema, package: str, imports: list[str]) -> str:
    lines = [HEADER, 'syntax = "proto3";', "", f"package {package};"]
    if imports:
        lines.append("")
        lines += [f'import "{file}";' for file in imports]
    for enum_spec in schema.enums.values():
        if enum_spec.package == package:
            lines += ["", *_render_enum(enum_spec)]
    for message in schema.messages.values():
        if message.package == package:
            lines += ["", *_render_message(schema, message)]
    for service in schema.services:
        if service.package == package:
            lines += ["", *_render_service(schema, service)]
    return "\n".join(lines) + "\n"


def _comment(doc: str | None, indent: str = "") -> list[str]:
    if not doc:
        return []
    return [f"{indent}// {line}".rstrip() for line in doc.splitlines()]


def _render_enum(spec: EnumSpec) -> Iterator[str]:
    yield from _comment(spec.doc)
    yield f"enum {spec.name} {{"
    numbers = [number for _, number in spec.values]
    if len(set(numbers)) < len(numbers):
        yield f"{INDENT}option allow_alias = true;"
    for name, number in spec.values:
        yield f"{INDENT}{name} = {number};"
    yield "}"


def _render_message(schema: ResolvedSchema, message: MessageSpec) -> Iterator[str]:
    yield from _comment(message.doc)
    yield f"message {message.name} {{"
    rendered_oneofs: set[str] = set()
    for spec in message.fields:
        if spec.oneof is None:
            yield from _render_field(schema, message, spec, INDENT)
            continue
        if spec.oneof in rendered_oneofs:
            continue
        rendered_oneofs.add(spec.oneof)
        yield f"{INDENT}oneof {spec.oneof} {{"
        for member in message.fields:
            if member.oneof == spec.oneof:
                yield from _render_field(schema, message, member, INDENT * 2, in_oneof=True)
        yield f"{INDENT}}}"
    if message.reserved:
        yield f"{INDENT}reserved {_ranges(message.reserved)};"
    if message.reserved_names:
        names = ", ".join(f'"{name}"' for name in message.reserved_names)
        yield f"{INDENT}reserved {names};"
    yield "}"


def _render_field(
    schema: ResolvedSchema,
    message: MessageSpec,
    spec: FieldSpec,
    indent: str,
    in_oneof: bool = False,
) -> Iterator[str]:
    yield from _comment(spec.doc, indent)
    type_name = _type_name(schema, message.package, spec.value)
    if spec.label == "map":
        declaration = f"map<{spec.map_key}, {type_name}>"
    elif spec.label == "repeated":
        declaration = f"repeated {type_name}"
    elif spec.label == "optional" and not in_oneof:
        declaration = f"optional {type_name}"
    else:
        declaration = type_name
    trailer = "  // json" if spec.carrier else ""
    yield f"{indent}{declaration} {spec.name} = {spec.number};{trailer}"


def _render_service(schema: ResolvedSchema, service: ServiceDef) -> Iterator[str]:
    yield from _comment(service.doc)
    yield f"service {service.name} {{"
    for method in service.methods:
        request = _type_name(schema, service.package, TypeRef("message", py=method.request))
        response = _type_name(schema, service.package, TypeRef("message", py=method.response))
        request = f"stream {request}" if method.client_streaming else request
        response = f"stream {response}" if method.server_streaming else response
        yield from _comment(method.doc, INDENT)
        yield f"{INDENT}rpc {method.name}({request}) returns ({response});"
    yield "}"


def _type_name(schema: ResolvedSchema, package: str, ref: TypeRef) -> str:
    if ref.kind == "scalar":
        return ref.name
    full_name = schema.full_name(ref)
    owner, _, name = full_name.rpartition(".")
    return name if owner == package else full_name


def _ranges(numbers: tuple[int, ...]) -> str:
    parts = []
    start = previous = numbers[0]
    for number in [*numbers[1:], None]:
        if number is not None and number == previous + 1:
            previous = number
            continue
        parts.append(str(start) if start == previous else f"{start} to {previous}")
        if number is not None:
            start = previous = number
    return ", ".join(parts)
