def test_a_model_shared_by_two_packages_needs_an_explicit_package() -> None:
    class Shared(BaseModel):
        a: int = 0

    registry = registry_of(rpc(Shared), package="a.v1")
    registry.add_service(ServiceDef("Other", "b.v1", (rpc(Shared),)))
    with pytest.raises(SchemaError, match=r"used from packages a\.v1 and b\.v1"):
        registry.build()


def test_two_classes_with_one_name_collide() -> None:
    def make() -> type[BaseModel]:
        class Twin(BaseModel):
            a: int = 0

        return Twin

    with pytest.raises(SchemaError, match=r"shop\.v1\.Twin is both"):
        registry_of(MethodDef("A", make(), make())).build()


def test_packages_importing_each_other_are_refused() -> None:
    class Ping(ProtoModel, package="a.v1"):
        pong: "Pong | None" = None

    class Pong(ProtoModel, package="b.v1"):
        ping: Ping | None = None

    Ping.model_rebuild()
    with pytest.raises(
        SchemaError,
        match=r"files import each other: a/v1/a\.proto -> b/v1/b\.proto -> a/v1/a\.proto",
    ):
        render(registry_of(rpc(Ping)).build())


