"""Render a `ResolvedSchema` as `.proto` text: one file per package, with its imports.

The text rendered here is exactly what gets compiled at startup and what `fastgrpc3
export` writes, so the exported contract never drifts from the served one.
"""

from collections.abc import Iterator

from fastgrpc3.schema.annotations import STANDARD_MESSAGES, FieldSpec, TypeRef
from fastgrpc3.schema.lock import MAX_FIELD_NUMBER
from fastgrpc3.schema.registry import (
    EnumSpec,
    MessageSpec,
    ResolvedSchema,
    SchemaError,
    ServiceDef,
)

__all__ = ["package_file", "render"]

ENUM_MAX = 2**31 - 1
HEADER = "// Generated by fastgrpc3 from Python models: edit the models, not this file."
INDENT = "  "


def package_file(package: str) -> str:
    """File holding a package: `orders.v1` -> `orders/v1/orders.proto`."""
    parts = package.split(".")
    names = [part for part in parts if not _is_version(part)] or parts
    return "/".join(parts) + f"/{names[-1]}.proto"


def render(schema: ResolvedSchema) -> dict[str, str]:
    """`.proto` text of every file, keyed by file name.

    An element goes into its `file=`, else into its parent's file, else into the file of its
    package (`package_file`).
    """
    layout = _Layout(schema)
    imports = {file: _imports(schema, layout, file) for file in layout.files}
    _check_no_cycle(imports)
    nested = _nested(schema)
    return {
        file: _render_file(schema, layout, nested, file, imports[file]) for file in layout.files
    }


class _Nested:
    """The enums and messages declared inside each message, by its full name."""

    def __init__(self) -> None:
        self.enums: dict[str, list[EnumSpec]] = {}
        self.messages: dict[str, list[MessageSpec]] = {}


def _nested(schema: ResolvedSchema) -> _Nested:
    nested = _Nested()
    for enum_spec in schema.enums.values():
        if (parent := schema.parent(enum_spec.full_name)) is not None:
            nested.enums.setdefault(parent, []).append(enum_spec)
    for message in schema.messages.values():
        if (parent := schema.parent(message.full_name)) is not None:
            nested.messages.setdefault(parent, []).append(message)
    return nested


def _is_version(part: str) -> bool:
    return part.startswith("v") and part[1:2].isdigit()


class _Layout:
    """The file of every message, enum and service, and the package of every file."""

    def __init__(self, schema: ResolvedSchema) -> None:
        self.schema = schema
        all_specs: list[MessageSpec | EnumSpec] = [
            *schema.messages.values(),
            *schema.enums.values(),
        ]
        self.specs = {
            spec.full_name: spec for spec in all_specs if spec.full_name not in STANDARD_MESSAGES
        }
        self.packages: dict[str, str] = {}
        for service in schema.services:
            self._place(self.service_file(service), service.package, service.full_name)
        for full_name in self.specs:
            self._place(self.file_of(full_name), schema.package_of(full_name), full_name)

    @property
    def files(self) -> list[str]:
        return list(self.packages)

    def _place(self, file: str, package: str, owner: str) -> None:
        if self.packages.setdefault(file, package) != package:
            raise SchemaError(
                f"{owner}: file {file} already holds package {self.packages[file]}, not {package}"
            )

    def file_of(self, full_name: str) -> str:
        if full_name in STANDARD_MESSAGES:
            return STANDARD_MESSAGES[full_name]
        explicit = self.specs[full_name].file
        parent = self.schema.parent(full_name)
        if parent is None:
            return explicit or package_file(self.schema.package_of(full_name))
        parent_file = self.file_of(parent)
        if explicit is not None and explicit != parent_file:
            raise SchemaError(f"{full_name}: a nested type lives in its parent's file")
        return parent_file

    def service_file(self, service: ServiceDef) -> str:
        return service.file or package_file(service.package)


def _imports(schema: ResolvedSchema, layout: _Layout, file: str) -> list[str]:
    files: set[str] = set()

    def add(ref: TypeRef) -> None:
        if ref.import_path is not None:
            files.add(ref.import_path)
        elif ref.kind in ("message", "enum"):
            files.add(layout.file_of(schema.full_name(ref)))

    for message in schema.messages.values():
        if message.full_name in layout.specs and layout.file_of(message.full_name) == file:
            for spec in message.fields:
                add(spec.value)
    for service in schema.services:
        if layout.service_file(service) == file:
            for method in service.methods:
                add(TypeRef("message", py=method.request))
                add(TypeRef("message", py=method.response))
    files.discard(file)
    return sorted(files)


def _check_no_cycle(imports: dict[str, list[str]]) -> None:
    state: dict[str, str] = {}

    def visit(file: str, path: list[str]) -> None:
        if state.get(file) == "done":
            return
        if state.get(file) == "active":
            cycle = " -> ".join([*path[path.index(file) :], file])
            raise SchemaError(f"files import each other: {cycle}; move shared models")
        state[file] = "active"
        for imported in imports[file]:
            if imported in imports:
                visit(imported, [*path, file])
        state[file] = "done"

    for file in imports:
        visit(file, [])


def _render_file(
    schema: ResolvedSchema, layout: _Layout, nested: _Nested, file: str, imports: list[str]
) -> str:
    package = layout.packages[file]
    lines = [HEADER, 'syntax = "proto3";', "", f"package {package};"]
    if imports:
        lines.append("")
        lines += [f'import "{imported}";' for imported in imports]
    for enum_spec in schema.enums.values():
        if _top_level(schema, layout, enum_spec.full_name, file):
            lines += ["", *_render_enum(enum_spec)]
    for message in schema.messages.values():
        if _top_level(schema, layout, message.full_name, file):
            lines += ["", *_render_message(schema, nested, message)]
    for service in schema.services:
        if layout.service_file(service) == file:
            lines += ["", *_render_service(schema, service)]
    return "\n".join(lines) + "\n"


def _top_level(schema: ResolvedSchema, layout: _Layout, full_name: str, file: str) -> bool:
    return (
        full_name in layout.specs
        and schema.parent(full_name) is None
        and layout.file_of(full_name) == file
    )


def _comment(doc: str | None, indent: str = "") -> list[str]:
    if not doc:
        return []
    return [f"{indent}// {line}".rstrip() for line in doc.splitlines()]


def _render_enum(spec: EnumSpec) -> Iterator[str]:
    yield from _comment(spec.doc)
    yield f"enum {spec.name} {{"
    numbers = [number for _, number in spec.values]
    if len(set(numbers)) < len(numbers):
        yield f"{INDENT}option allow_alias = true;"
    for name, number in spec.values:
        yield f"{INDENT}{name} = {number};"
    yield from _render_reserved(spec.reserved, spec.reserved_names, ENUM_MAX)
    yield "}"


def _render_message(schema: ResolvedSchema, nested: _Nested, message: MessageSpec) -> Iterator[str]:
    yield from _comment(message.doc)
    yield f"message {message.name} {{"
    rendered_oneofs: set[str] = set()
    for spec in message.fields:
        if spec.oneof is None:
            yield from _render_field(schema, message, spec, INDENT)
            continue
        if spec.oneof in rendered_oneofs:
            continue
        rendered_oneofs.add(spec.oneof)
        yield f"{INDENT}oneof {spec.oneof} {{"
        for member in message.fields:
            if member.oneof == spec.oneof:
                yield from _render_field(schema, message, member, INDENT * 2, in_oneof=True)
        yield f"{INDENT}}}"
    yield from _render_reserved(message.reserved, message.reserved_names, MAX_FIELD_NUMBER)
    # Nested types, as in `message A { message B {} }`.
    for enum_spec in nested.enums.get(message.full_name, ()):
        yield ""
        yield from (f"{INDENT}{line}".rstrip() for line in _render_enum(enum_spec))
    for child in nested.messages.get(message.full_name, ()):
        yield ""
        lines = _render_message(schema, nested, child)
        yield from (f"{INDENT}{line}".rstrip() for line in lines)
    yield "}"


def _render_field(
    schema: ResolvedSchema,
    message: MessageSpec,
    spec: FieldSpec,
    indent: str,
    in_oneof: bool = False,
) -> Iterator[str]:
    yield from _comment(spec.doc, indent)
    type_name = _type_name(schema, schema.package_of(message.full_name), spec.value)
    if spec.label == "map":
        declaration = f"map<{spec.map_key}, {type_name}>"
    elif spec.label == "repeated":
        declaration = f"repeated {type_name}"
    elif spec.label == "optional" and not in_oneof:
        declaration = f"optional {type_name}"
    else:
        declaration = type_name
    trailer = "  // json" if spec.carrier else ""
    yield f"{indent}{declaration} {spec.wire_name} = {spec.number};{trailer}"


def _render_service(schema: ResolvedSchema, service: ServiceDef) -> Iterator[str]:
    yield from _comment(service.doc)
    yield f"service {service.name} {{"
    for method in service.methods:
        request = _type_name(schema, service.package, TypeRef("message", py=method.request))
        response = _type_name(schema, service.package, TypeRef("message", py=method.response))
        request = f"stream {request}" if method.client_streaming else request
        response = f"stream {response}" if method.server_streaming else response
        yield from _comment(method.doc, INDENT)
        yield f"{INDENT}rpc {method.name}({request}) returns ({response});"
    yield "}"


def _type_name(schema: ResolvedSchema, package: str, ref: TypeRef) -> str:
    if ref.kind == "scalar":
        return ref.name
    full_name = schema.full_name(ref)
    if schema.package_of(full_name) == package:
        # Relative to the package: `Order` or, for a nested type, `Order.Card`.
        return full_name.removeprefix(f"{package}.")
    return full_name


def _render_reserved(
    ranges: tuple[tuple[int, int], ...], names: tuple[str, ...], maximum: int
) -> Iterator[str]:
    if ranges:
        parts = []
        for start, end in ranges:
            if start == end:
                parts.append(str(start))
            else:
                parts.append(f"{start} to {'max' if end == maximum else end}")
        yield f"{INDENT}reserved {', '.join(parts)};"
    if names:
        yield f"{INDENT}reserved {', '.join(f'"{name}"' for name in names)};"
