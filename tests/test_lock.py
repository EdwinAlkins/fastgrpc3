"""`proto.lock`: number assignment, reserved numbers, file format."""

from pathlib import Path

import pytest

from fastgrpc3.schema.lock import Change, Lock, LockError, MessageLock, assign_numbers

MESSAGE = "shop.v1.Order"


def test_new_fields_are_numbered_in_declaration_order() -> None:
    entry, changes = assign_numbers(MESSAGE, [("a", None), ("b", None)], None)
    assert entry == MessageLock({"a": 1, "b": 2})
    assert changes == [Change("added", MESSAGE, "a", 1), Change("added", MESSAGE, "b", 2)]


def test_a_field_inserted_first_gets_the_next_number_not_its_position() -> None:
    previous = MessageLock({"a": 1, "b": 2})
    entry, changes = assign_numbers(MESSAGE, [("new", None), ("a", None), ("b", None)], previous)
    assert entry.fields == {"a": 1, "b": 2, "new": 3}
    assert changes == [Change("added", MESSAGE, "new", 3)]


def test_a_removed_field_reserves_its_number_and_name() -> None:
    previous = MessageLock({"a": 1, "b": 2})
    entry, changes = assign_numbers(MESSAGE, [("a", None), ("c", None)], previous)
    assert entry == MessageLock({"a": 1, "c": 3}, reserved=[2], reserved_names=["b"])
    assert Change("removed", MESSAGE, "b", 2) in changes


def test_a_re_added_name_gets_a_fresh_number() -> None:
    previous = MessageLock({"a": 1}, reserved=[2], reserved_names=["b"])
    entry, _ = assign_numbers(MESSAGE, [("a", None), ("b", None)], previous)
    assert entry == MessageLock({"a": 1, "b": 3}, reserved=[2])


def test_explicit_numbers_win_and_a_renumbered_field_reserves_its_old_number() -> None:
    previous = MessageLock({"a": 1, "b": 2})
    entry, changes = assign_numbers(MESSAGE, [("a", 5), ("b", None)], previous)
    assert entry == MessageLock({"a": 5, "b": 2}, reserved=[1])
    assert changes == [Change("renumbered", MESSAGE, "a", 5)]


def test_new_numbers_fill_gaps_never_used() -> None:
    previous = MessageLock({"a": 1}, reserved=[2])
    entry, _ = assign_numbers(MESSAGE, [("a", None), ("b", 5), ("c", None), ("d", None)], previous)
    assert entry.fields == {"a": 1, "b": 5, "c": 3, "d": 4}


def test_new_numbers_skip_the_range_reserved_by_protobuf() -> None:
    previous = MessageLock(reserved=list(range(1, 19000)))
    entry, _ = assign_numbers(MESSAGE, [("a", None)], previous)
    assert entry.fields == {"a": 20000}


@pytest.mark.parametrize(
    ("fields", "previous", "message"),
    [
        ([("a", 1), ("b", 1)], None, "used by both a and b"),
        ([("a", 2), ("b", None)], MessageLock({"a": 1, "b": 2}), "used by both a and b"),
        ([("a", 2)], MessageLock({"a": 1}, reserved=[2]), "belonged to a removed field"),
        ([("a", 0)], None, "not in 1"),
        ([("a", 2**29)], None, "not in 1"),
        ([("a", 19500)], None, "19000-19999"),
    ],
)
def test_invalid_numbers_are_refused(
    fields: list[tuple[str, int | None]], previous: MessageLock | None, message: str
) -> None:
    with pytest.raises(LockError, match=message):
        assign_numbers(MESSAGE, fields, previous)


def test_unlocked_error_refuses_to_invent_a_number() -> None:
    previous = MessageLock({"a": 1})
    assign_numbers(MESSAGE, [("a", None), ("b", 2)], previous, unlocked="error")
    with pytest.raises(LockError, match=r"no field number for shop\.v1\.Order\.c"):
        assign_numbers(MESSAGE, [("a", None), ("c", None)], previous, unlocked="error")


def test_lock_file_round_trip() -> None:
    lock = Lock(
        {
            "shop.v1.Order": MessageLock({"b": 2, "a": 1}, reserved=[4, 3], reserved_names=["x"]),
            "shop.v1.Empty": MessageLock(),
        }
    )
    text = lock.dumps()
    assert text == (
        "# proto.lock — generated by `fastgrpc3 lock`, commit it\n"
        "version = 1\n"
        "\n"
        '[messages."shop.v1.Empty".fields]\n'
        "\n"
        '[messages."shop.v1.Order"]\n'
        "reserved = [3, 4]\n"
        'reserved_names = ["x"]\n'
        "\n"
        '[messages."shop.v1.Order".fields]\n'
        "a = 1\n"
        "b = 2\n"
    )
    assert Lock.loads(text).dumps() == text


def test_missing_lock_file_is_empty(tmp_path: Path) -> None:
    assert Lock.load(tmp_path / "proto.lock") == Lock()


@pytest.mark.parametrize(("text", "message"), [("version = 2", "version 2"), ("[", "invalid")])
def test_bad_lock_files_are_refused(text: str, message: str) -> None:
    with pytest.raises(LockError, match=message):
        Lock.loads(text)
