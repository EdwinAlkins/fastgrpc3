@pytest.fixture(scope="module")
def files() -> dict[str, str]:
    return generate([PROTOS])


@pytest.fixture
def package(files: dict[str, str], tmp_path: Path) -> Iterator[tuple[str, Path]]:
    """The generated files written as an importable package under a fresh name."""
    name = f"generated_{next(_packages)}"
    write(files, tmp_path / name)
    sys.path.insert(0, str(tmp_path))
    yield name, tmp_path / name
    sys.path.remove(str(tmp_path))
    for module in [m for m in sys.modules if m == name or m.startswith(f"{name}.")]:
        del sys.modules[module]


def load(package: tuple[str, Path], module: str) -> ModuleType:
    return importlib.import_module(f"{package[0]}.{module}")


