"""Source of the generated modules: `<file>_models.py` and `<file>_service.py`.

Generated models are ordinary code-first models (`ProtoModel`, `field(n)`, markers), so
rendering them back gives the same contract (criterion R2).
"""

from collections import defaultdict
from dataclasses import dataclass, field

from protoruf import Schema
from protoruf.schema import EnumInfo, FieldInfo, MessageInfo

from fastgrpc3.codegen.naming import class_name, enum_member_names, field_name, module_parts
from fastgrpc3.codegen.source import INDENT, Imports, blank_separated, call, docstring

__all__ = ["HEADER", "Index", "models_module", "services_module", "string_literal"]

HEADER = "# Generated by fastgrpc3"
TYPES = "fastgrpc3.types"

_SCALARS = {
    "double": ("", "float"),
    "float": (TYPES, "Float32"),
    "int64": ("", "int"),
    "int32": (TYPES, "Int32"),
    "uint32": (TYPES, "UInt32"),
    "uint64": (TYPES, "UInt64"),
    "sint32": (TYPES, "SInt32"),
    "sint64": (TYPES, "SInt64"),
    "fixed32": (TYPES, "Fixed32"),
    "fixed64": (TYPES, "Fixed64"),
    "sfixed32": (TYPES, "SFixed32"),
    "sfixed64": (TYPES, "SFixed64"),
    "bool": ("", "bool"),
    "string": ("", "str"),
    "bytes": ("", "bytes"),
}
_ZEROS = {"bool": "False", "string": '""', "bytes": 'b""', "double": "0.0", "float": "0.0"}

# Well-known messages -> (module, name) of their Python type; "" is a builtin expression.
_WELL_KNOWN = {
    "google.protobuf.Timestamp": ("datetime", "datetime.datetime"),
    "google.protobuf.Duration": ("datetime", "datetime.timedelta"),
    "google.type.Date": ("datetime", "datetime.date"),
    "google.protobuf.Value": ("pydantic", "JsonValue"),
    "google.protobuf.ListValue": (TYPES, "ListValue"),
    "google.protobuf.FieldMask": (TYPES, "FieldMask"),
    "google.protobuf.Empty": (TYPES, "Empty"),
    "google.protobuf.Any": (TYPES, "AnyMessage"),
    **{
        f"google.protobuf.{name}": (TYPES, name)
        for name in (
            "DoubleValue", "FloatValue", "Int64Value", "UInt64Value", "Int32Value",
            "UInt32Value", "BoolValue", "StringValue", "BytesValue",
        )
    },
}  # fmt: skip
# Files whose types all map to Python types: never generated.
NATIVE_FILES = frozenset({"google/type/date.proto"})


def is_generated(file: str) -> bool:
    """Whether a `.proto` file of the descriptor gets Python modules."""
    return not file.startswith("google/protobuf/") and file not in NATIVE_FILES


@dataclass
class Index:
    """Python location of every generated message and enum, across all files."""

    schema: Schema
    classes: dict[str, tuple[str, str]] = field(default_factory=dict)
    members: dict[str, tuple[list[str], str | None]] = field(default_factory=dict)
    children: dict[str | None, list[str]] = field(default_factory=lambda: defaultdict(list))

    @classmethod
    def build(cls, schema: Schema, files: list[str]) -> "Index":
        index = cls(schema)
        infos: list[MessageInfo | EnumInfo] = [*schema.messages.values(), *schema.enums.values()]
        for info in infos:
            if info.file not in files or getattr(info, "is_map_entry", False):
                continue
            package = schema.files[info.file].package
            local = info.full_name.removeprefix(f"{package}.") if package else info.full_name
            *parents, short_name = local.split(".")
            name = class_name(short_name, tuple(parents))
            index.classes[info.full_name] = (info.file, name)
            index.children[info.parent].append(info.full_name)
        for info in schema.enums.values():
            if info.full_name in index.classes:
                values = [value.name for value in info.values]
                index.members[info.full_name] = enum_member_names(info.name, values)
        return index

    def file_classes(self, file: str) -> list[str]:
        """Full names of the classes of a file, parents before their nested types."""
        ordered: list[str] = []

        def visit(parent: str | None) -> None:
            for full_name in self.children.get(parent, []):
                if self.classes[full_name][0] == file:
                    ordered.append(full_name)
                visit(full_name)

        visit(None)
        return ordered


def models_module(index: Index, file: str) -> str:
    """Source of `<file>_models.py`."""
    classes = index.file_classes(file)
    module = _Module(index, file, Imports(taken={index.classes[n][1] for n in classes}))
    enums = [index.schema.enums[n] for n in classes if n in index.schema.enums]
    messages = [index.schema.messages[n] for n in classes if n in index.schema.messages]
    blocks = [module.enum_class(info) for info in enums]
    blocks += [module.message_class(info) for info in messages]
    position = {info.full_name: i for i, info in enumerate(messages)}
    rebuilds = [
        f"{index.classes[info.full_name][1]}.model_rebuild()"
        for i, info in enumerate(messages)
        if any(position.get(ref, -1) >= i for ref in _message_refs(info))
    ]
    if rebuilds:
        blocks.append(rebuilds)
    return module.source(f'"""Models of {file}."""', blocks)


def services_module(index: Index, file: str) -> str:
    """Source of `<file>_service.py`: one `ServiceDef` per service."""
    module = _Module(index, file, Imports(taken=set()), import_own_models=True)
    blocks = []
    for full_name in index.schema.files[file].services:
        service = index.schema.service(full_name)
        package = index.schema.files[file].package
        methods = []
        for method in service.methods:
            args = [string_literal(method.name), module.ref(method.input_type)]
            args.append(module.ref(method.output_type))
            if method.client_streaming:
                args.append("client_streaming=True")
            if method.server_streaming:
                args.append("server_streaming=True")
            if method.comments and method.comments.text:
                args.append(f"doc={string_literal(method.comments.text)}")
            methods += call(module.imports.use("fastgrpc3", "MethodDef"), args, ",", INDENT * 2)
        service_def = module.imports.use("fastgrpc3", "ServiceDef")
        lines = [
            f"{service.name} = {service_def}(",
            f"{INDENT}{string_literal(service.name)},",
            f"{INDENT}{string_literal(package)},",
            f"{INDENT}(",
            *methods,
            f"{INDENT}),",
        ]
        if service.comments and service.comments.text:
            lines.append(f"{INDENT}doc={string_literal(service.comments.text)},")
        blocks.append([*lines, ")"])
    return module.source(f'"""Services of {file}."""', blocks)


def string_literal(text: str) -> str:
    """A double-quoted Python string literal."""
    escapes = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    return '"' + "".join(escapes.get(char, char) for char in text) + '"'


@dataclass
class _Module:
    index: Index
    file: str
    imports: Imports
    # The services module refers to the models of its own file through an import.
    import_own_models: bool = False

    def source(self, doc: str, blocks: list[list[str]]) -> str:
        body = list(blank_separated(blocks))
        head = [f"{HEADER} from {self.file}: do not edit.", doc, "", *self.imports.lines()]
        # isort: two blank lines before a class, one before any other statement.
        gap = ["", ""] if body[0].startswith("class ") else [""]
        return "\n".join([*head, *gap, *body]) + "\n"

    def ref(self, full_name: str) -> str:
        """Python expression naming a message or enum type."""
        if full_name == "google.protobuf.Struct":
            return f"dict[str, {self.imports.use('typing', 'Any')}]"
        if full_name in _WELL_KNOWN:
            module, name = _WELL_KNOWN[full_name]
            if module == "datetime":
                return f"{self.imports.module('datetime')}.{name.split('.')[1]}"
            return self.imports.use(module, name)
        if full_name not in self.index.classes:
            raise ValueError(f"{self.file}: type {full_name} is not supported")
        file, name = self.index.classes[full_name]
        if file == self.file and not self.import_own_models:
            return name
        return f"{self._import_module(file)}.{name}"

    def _import_module(self, file: str) -> str:
        own_dirs, _ = module_parts(self.file)
        dirs, stem = module_parts(file)
        common = 0
        while common < min(len(own_dirs), len(dirs)) and own_dirs[common] == dirs[common]:
            common += 1
        alias = "_" + "_".join((*dirs, stem))
        dots = len(own_dirs) - common + 1
        package = ".".join(dirs[common:])
        return self.imports.relative_module(dots, package, f"{stem}_models", alias)

    def enum_class(self, info: EnumInfo) -> list[str]:
        name = self.index.classes[info.full_name][1]
        members, prefix = self.index.members[info.full_name]
        args = [self.imports.use(TYPES, "ProtoEnum"), f"proto={string_literal(info.full_name)}"]
        if prefix is not None:
            args.append(f"prefix={string_literal(prefix)}")
        lines = call(f"class {name}", args, ":")
        if info.comments and info.comments.text:
            lines += [*docstring(info.comments.text, INDENT), ""]
        for member, value in zip(members, info.values, strict=True):
            if value.comments and value.comments.text:
                lines += [f"{INDENT}# {line}".rstrip() for line in value.comments.text.splitlines()]
            lines.append(f"{INDENT}{member} = {value.number}")
        return lines

    def message_class(self, info: MessageInfo) -> list[str]:
        name = self.index.classes[info.full_name][1]
        args = [self.imports.use(TYPES, "ProtoModel"), f"proto={string_literal(info.full_name)}"]
        lines = call(f"class {name}", args, ":")
        if info.comments and info.comments.text:
            lines += docstring(info.comments.text, INDENT)
            if info.fields:
                lines.append("")
        taken: set[str] = set()
        for proto_field in info.fields:
            lines += self.field_line(proto_field, field_name(proto_field.name, taken))
        if len(lines) == 1:
            lines.append(f"{INDENT}pass")
        return lines

    def field_line(self, info: FieldInfo, name: str) -> list[str]:
        annotation, default = self.annotation(info)
        args = [str(info.number), default]
        if info.oneof:
            args.append(f"oneof={string_literal(info.oneof)}")
        if name != info.name:
            args.append(f"proto_name={string_literal(info.name)}")
        if info.comments and info.comments.text:
            args.append(f"description={string_literal(info.comments.text)}")
        prefix = f"{name}: {annotation} = {self.imports.use(TYPES, 'field')}"
        return call(prefix, args, indent=INDENT)

    def annotation(self, info: FieldInfo) -> tuple[str, str]:
        """Python annotation of a field, and its `default=` / `default_factory=` argument."""
        if info.is_map:
            key = self.value_type(info.map_key_kind or "", None)
            value = self.value_type(info.map_value_kind or "", info.map_value_type_name)
            return f"dict[{key}, {value}]", "default_factory=dict"
        value = self.value_type(info.kind, info.type_name)
        if info.is_list:
            return f"list[{value}]", "default_factory=list"
        if info.type_name == "google.protobuf.Value":
            return value, "default=None"  # `JsonValue` already admits None
        if info.kind == "message" or info.has_presence:
            return f"{value} | None", "default=None"
        if info.kind == "enum":
            return value, f"default={value}.{self.zero_member(info.type_name or '')}"
        return value, f"default={_ZEROS.get(info.kind, '0')}"

    def value_type(self, kind: str, type_name: str | None) -> str:
        if kind in ("message", "enum"):
            return self.ref(type_name or "")
        module, name = _SCALARS[kind]
        return self.imports.use(module, name) if module else name

    def zero_member(self, enum_name: str) -> str:
        members, _ = self.index.members[enum_name]
        values = self.index.schema.enums[enum_name].values
        return next(m for m, v in zip(members, values, strict=True) if v.number == 0)


def _message_refs(info: MessageInfo) -> list[str]:
    refs = []
    for proto_field in info.fields:
        type_name = proto_field.map_value_type_name if proto_field.is_map else proto_field.type_name
        if type_name and (proto_field.kind == "message" or proto_field.map_value_kind == "message"):
            refs.append(type_name)
    return refs
